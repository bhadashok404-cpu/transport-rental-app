/**
 * Search India locations by query string.
 * Returns up to `limit` results sorted by relevance:
 *   1. Exact start-of-word match
 *   2. Contains match
 * @param {string} query
 * @param {number} [limit=10]
 * @returns {{ name: string, state: string, type: string }[]}
 */
export function searchLocations(query, limit = 10) {
  if (!query || query.trim().length < 2) return [];
  const q = query.trim().toLowerCase();

  const startsWith = [];
  const contains   = [];

  for (const loc of LOCATIONS) {
    const name = loc.name.toLowerCase();
    if (name.startsWith(q)) {
      startsWith.push(loc);
    } else if (name.includes(q)) {
      contains.push(loc);
    }
    if (startsWith.length + contains.length >= limit * 3) break; // early exit
  }

  // merge and deduplicate by name+state
  return [...startsWith, ...contains]
    .slice(0, limit);
}
